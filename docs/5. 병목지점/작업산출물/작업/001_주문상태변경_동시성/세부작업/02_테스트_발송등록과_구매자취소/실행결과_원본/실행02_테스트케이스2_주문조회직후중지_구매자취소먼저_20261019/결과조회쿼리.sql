-- 1. 기준 2: 지갑 잔액과 잔액 변동 내역 합계가 다른 회원
SELECT w.MEMBER_ID, w.BALANCE, NVL(SUM(t.AMOUNT), 0) AS LEDGER_SUM
  FROM WALLET w
  LEFT JOIN BALANCE_TRANSACTION t ON t.MEMBER_ID = w.MEMBER_ID
 WHERE w.MEMBER_ID IN ('s1-2c2seller01', 's1-2c2buyer01')
 GROUP BY w.MEMBER_ID, w.BALANCE
HAVING w.BALANCE <> NVL(SUM(t.AMOUNT), 0);

-- 2. 기준 3: 반환·지급 내역의 건수와 종류가 거래 상태와 맞지 않는 주문
SELECT o.ORDER_ID, o.TRADE_STATUS,
       SUM(CASE WHEN t.TYPE = 'CANCEL_REFUND' THEN 1 ELSE 0 END) AS CANCEL_REFUND_CNT,
       SUM(CASE WHEN t.TYPE = 'REFUND'        THEN 1 ELSE 0 END) AS REFUND_CNT,
       SUM(CASE WHEN t.TYPE = 'SALE_PAYOUT'   THEN 1 ELSE 0 END) AS SALE_PAYOUT_CNT
  FROM PURCHASE_ORDER o
  LEFT JOIN BALANCE_TRANSACTION t
         ON t.ORDER_ID = o.ORDER_ID
        AND t.TYPE IN ('CANCEL_REFUND', 'REFUND', 'SALE_PAYOUT')
 WHERE o.ORDER_ID = 44
 GROUP BY o.ORDER_ID, o.TRADE_STATUS
HAVING NOT (
        (o.TRADE_STATUS IN ('IN_PROGRESS', 'ON_HOLD') AND COUNT(t.TRANSACTION_ID) = 0)
     OR (o.TRADE_STATUS = 'CANCELLED' AND COUNT(t.TRANSACTION_ID) = 1
         AND SUM(CASE WHEN t.TYPE = 'CANCEL_REFUND' THEN 1 ELSE 0 END) = 1)
     OR (o.TRADE_STATUS = 'REFUNDED' AND COUNT(t.TRANSACTION_ID) = 1
         AND SUM(CASE WHEN t.TYPE = 'REFUND' THEN 1 ELSE 0 END) = 1)
     OR (o.TRADE_STATUS = 'COMPLETED' AND COUNT(t.TRANSACTION_ID) = 1
         AND SUM(CASE WHEN t.TYPE = 'SALE_PAYOUT' THEN 1 ELSE 0 END) = 1));

-- 3. 기준 4: 거래 상태·배송 상태와 발송 정보 유무가 맞지 않는 주문
SELECT o.ORDER_ID, o.TRADE_STATUS, o.SHIPPING_STATUS, COUNT(s.SHIPMENT_ID) AS SHIPMENT_CNT
  FROM PURCHASE_ORDER o
  LEFT JOIN SHIPMENT s ON s.ORDER_ID = o.ORDER_ID
 WHERE o.ORDER_ID = 44
 GROUP BY o.ORDER_ID, o.TRADE_STATUS, o.SHIPPING_STATUS
HAVING (o.TRADE_STATUS = 'CANCELLED' AND COUNT(s.SHIPMENT_ID) > 0)
    OR (o.SHIPPING_STATUS IN ('SHIPPING', 'DELIVERED') AND COUNT(s.SHIPMENT_ID) = 0)
    OR (o.SHIPPING_STATUS = 'WAITING_SHIPMENT' AND COUNT(s.SHIPMENT_ID) > 0);

-- 4. 기준 5: 환불 요청의 처리 결과와 거래 상태가 맞지 않는 주문
SELECT o.ORDER_ID, o.TRADE_STATUS, o.COMPLETION_CAUSE, r.DECISION
  FROM PURCHASE_ORDER o
  JOIN REFUND_REQUEST r ON r.ORDER_ID = o.ORDER_ID
 WHERE o.ORDER_ID = 44
   AND NOT ((r.DECISION = 'PENDING' AND o.TRADE_STATUS = 'ON_HOLD')
         OR (r.DECISION IN ('APPROVED', 'AUTO_APPROVED') AND o.TRADE_STATUS = 'REFUNDED')
         OR (r.DECISION = 'REJECTED' AND o.TRADE_STATUS = 'COMPLETED'
             AND o.COMPLETION_CAUSE = 'REFUND_REJECTED'));
