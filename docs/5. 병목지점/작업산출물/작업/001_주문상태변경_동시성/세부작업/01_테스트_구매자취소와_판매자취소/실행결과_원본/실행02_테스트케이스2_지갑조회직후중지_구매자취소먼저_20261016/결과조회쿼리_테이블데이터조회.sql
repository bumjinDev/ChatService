-- 1. 회원 MEMBERTBL
SELECT ID, NICKNAME, JOINDATE
  FROM MEMBERTBL
 WHERE ID IN ('s1-1c3seller02', 's1-1c3buyer02');

-- 2. 상품 PRODUCT
SELECT PRODUCT_ID, SELLER_ID, NAME, PRICE, INITIAL_QUANTITY, REMAINING_QUANTITY, STATUS
  FROM PRODUCT
 WHERE SELLER_ID = 's1-1c3seller02';

-- 3. 주문 PURCHASE_ORDER
SELECT ORDER_ID, PRODUCT_ID, BUYER_ID, SELLER_ID, PAID_AMOUNT, TRADE_STATUS, SHIPPING_STATUS, CANCELLED_BY, CANCEL_REASON
  FROM PURCHASE_ORDER
 WHERE BUYER_ID = 's1-1c3buyer02';

-- 4. 지갑 WALLET
SELECT MEMBER_ID, BALANCE
  FROM WALLET
 WHERE MEMBER_ID IN ('s1-1c3seller02', 's1-1c3buyer02');

-- 5. 잔액 변동 내역 BALANCE_TRANSACTION
SELECT TRANSACTION_ID, MEMBER_ID, TYPE, AMOUNT, BALANCE_AFTER, ORDER_ID, CREATED_AT
  FROM BALANCE_TRANSACTION
 WHERE MEMBER_ID IN ('s1-1c3seller02', 's1-1c3buyer02')
 ORDER BY TRANSACTION_ID;
 