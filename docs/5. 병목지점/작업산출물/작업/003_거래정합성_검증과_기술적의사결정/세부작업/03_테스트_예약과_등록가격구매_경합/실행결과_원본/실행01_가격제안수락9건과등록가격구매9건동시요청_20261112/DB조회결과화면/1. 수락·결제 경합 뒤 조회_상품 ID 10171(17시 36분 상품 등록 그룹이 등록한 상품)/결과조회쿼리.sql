-- 대상 상품: 판매자 rsvbuy01seller가 마지막으로 등록한 상품(「준비: 상품 등록」 그룹이 등록한 상품)
-- 예약 기간이 20분이므로 수락·결제 경합 뒤 20분 안에 조회한다.

-- 상품
SELECT PRODUCT_ID, PRICE, INITIAL_QUANTITY, REMAINING_QUANTITY, STATUS, SOLD_AT
  FROM PRODUCT
 WHERE PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller');

-- 가격 제안 9건
SELECT OFFER_ID, CONVERSATION_ID, BUYER_ID, AMOUNT, QUANTITY, STATUS, CREATED_AT, RESPONDED_AT
  FROM PRICE_OFFER
 WHERE PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')
 ORDER BY OFFER_ID;

-- 예약
SELECT RESERVATION_ID, OFFER_ID, CONVERSATION_ID, BUYER_ID, SELLER_ID, QUANTITY, STATUS,
       RESERVED_AT, EXPIRES_AT, ENDED_AT
  FROM RESERVATION
 WHERE PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')
 ORDER BY RESERVATION_ID;

-- 가격 제안과 예약 대조: 수락한 가격 제안마다 같은 구매자에게 제안 수량 전부가 예약됐는지,
-- 응답 대기로 남은 가격 제안에 예약이 없는지
SELECT o.OFFER_ID, o.BUYER_ID, o.QUANTITY AS OFFER_QTY, o.STATUS AS OFFER_STATUS,
       r.RESERVATION_ID, r.BUYER_ID AS RSV_BUYER, r.CONVERSATION_ID AS RSV_CONV,
       o.CONVERSATION_ID AS OFFER_CONV, r.QUANTITY AS RSV_QTY, r.STATUS AS RSV_STATUS
  FROM PRICE_OFFER o
  LEFT JOIN RESERVATION r ON r.OFFER_ID = o.OFFER_ID
 WHERE o.PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')
 ORDER BY o.OFFER_ID;

-- 주문
SELECT ORDER_ID, BUYER_ID, QUANTITY, UNIT_PRICE, PAID_AMOUNT, PRICE_SOURCE, OFFER_ID,
       TRADE_STATUS, SHIPPING_STATUS, CONFIRMED_AT, REQUEST_ID
  FROM PURCHASE_ORDER
 WHERE PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')
 ORDER BY ORDER_ID;

-- 유효 예약 합계와 주문 수량 합계
-- 유효 예약: 예약 중 상태이면서 만료 시각이 지금보다 뒤인 예약. 만료 시각은 UTC로 저장되어 있다.
SELECT (SELECT COUNT(*) FROM RESERVATION
         WHERE PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')
           AND STATUS = 'ACTIVE' AND EXPIRES_AT > SYS_EXTRACT_UTC(SYSTIMESTAMP)) AS ACTIVE_COUNT,
       (SELECT NVL(SUM(QUANTITY), 0) FROM RESERVATION
         WHERE PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')
           AND STATUS = 'ACTIVE' AND EXPIRES_AT > SYS_EXTRACT_UTC(SYSTIMESTAMP)) AS ACTIVE_SUM,
       (SELECT COUNT(*) FROM PURCHASE_ORDER
         WHERE PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')) AS ORDER_COUNT,
       (SELECT NVL(SUM(QUANTITY), 0) FROM PURCHASE_ORDER
         WHERE PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')) AS ORDER_QUANTITY_SUM
  FROM DUAL;

-- 등록 가격 구매자 9명의 잔액과 주문 대조
SELECT w.MEMBER_ID, w.BALANCE, o.ORDER_ID, o.QUANTITY, o.PAID_AMOUNT
  FROM WALLET w
  LEFT JOIN PURCHASE_ORDER o
    ON o.BUYER_ID = w.MEMBER_ID
   AND o.PRODUCT_ID = (SELECT MAX(PRODUCT_ID) FROM PRODUCT WHERE SELLER_ID = 'rsvbuy01seller')
 WHERE w.MEMBER_ID LIKE 'rsvbuy01buy%'
 ORDER BY w.MEMBER_ID;

-- 등록 가격 구매자 9명의 잔액 변동 내역(충전과 결제)
SELECT TRANSACTION_ID, MEMBER_ID, TYPE, AMOUNT, BALANCE_AFTER, ORDER_ID, CREATED_AT
  FROM BALANCE_TRANSACTION
 WHERE MEMBER_ID LIKE 'rsvbuy01buy%'
 ORDER BY MEMBER_ID, TRANSACTION_ID;
