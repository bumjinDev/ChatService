-- 세부 작업 04 실행03 「기존 거래 상품의 수락 1건과 다수 등록 가격 결제」의 읽기 전용 확인 조회
--
-- 쓰는 때
-- - JMeter의 DB 조회가 실패했거나, 검증 요청 직전·직후에 DB 조회 도구로 직접 확인할 때
-- - 실행할 때 :product_id에 대상 상품 ID(이 폴더의 실행03_상품과대화.csv에 있는 product_id 열의 값)를 넣는다
-- 이 파일은 SELECT만 실행한다. 첫 문장으로 읽기 전용 트랜잭션을 시작하고, 마지막에 ROLLBACK으로 끝낸다.
-- 대상 상품 전체를 조회한다. 성공 응답에 나온 ID만 조회하지 않는다.
-- 유효 예약은 예약 중(ACTIVE)이면서 만료 시각이 DB의 현재 시각(UTC)보다 뒤인 예약이다. 실행01의 JMeter 조회와 같은 기준이다.

SET TRANSACTION READ ONLY;

-- 0. 조회 시각(UTC)
SELECT TO_CHAR(SYS_EXTRACT_UTC(SYSTIMESTAMP), 'YYYY-MM-DD"T"HH24:MI:SS.FF6"Z"') AS DB_NOW_UTC FROM DUAL;

-- 1. 상품
SELECT PRODUCT_ID, SELLER_ID, NAME, PRICE, INITIAL_QUANTITY, REMAINING_QUANTITY, STATUS, CREATED_AT, SOLD_AT
FROM PRODUCT WHERE PRODUCT_ID = :product_id;

-- 2. 대화(구매자마다 1건이어야 한다)
SELECT CONVERSATION_ID, PRODUCT_ID, BUYER_ID, SELLER_ID, CREATED_BY_SYSTEM, CREATED_AT
FROM CONVERSATION WHERE PRODUCT_ID = :product_id ORDER BY CONVERSATION_ID;

-- 3. 가격 제안(기존 예약 구매자의 4개 제안, 새 흥정 구매자의 2개 제안 두 건)
SELECT OFFER_ID, CONVERSATION_ID, BUYER_ID, SELLER_ID, AMOUNT, QUANTITY, STATUS, REQUEST_ID, CREATED_AT, RESPONDED_AT
FROM PRICE_OFFER WHERE PRODUCT_ID = :product_id ORDER BY OFFER_ID;

-- 4. 예약(대상 상품 전체, 유효 여부 포함)
SELECT RESERVATION_ID, CONVERSATION_ID, BUYER_ID, SELLER_ID, OFFER_ID, QUANTITY, STATUS,
       TO_CHAR(RESERVED_AT, 'YYYY-MM-DD"T"HH24:MI:SS.FF6"Z"') AS RESERVED_AT,
       TO_CHAR(EXPIRES_AT, 'YYYY-MM-DD"T"HH24:MI:SS.FF6"Z"') AS EXPIRES_AT,
       ENDED_AT, RELEASED_BY, FULFILLED_ORDER_ID,
       CASE WHEN STATUS = 'ACTIVE' AND EXPIRES_AT > SYS_EXTRACT_UTC(SYSTIMESTAMP) THEN '유효' ELSE '유효 아님' END AS VALID_NOW
FROM RESERVATION WHERE PRODUCT_ID = :product_id ORDER BY RESERVATION_ID;

-- 5. 주문(대상 상품 전체)
SELECT ORDER_ID, BUYER_ID, SELLER_ID, QUANTITY, UNIT_PRICE, PAID_AMOUNT, PRICE_SOURCE, OFFER_ID, TRADE_STATUS, SHIPPING_STATUS,
       CONFIRMED_AT, SHIP_DEADLINE_AT, REQUEST_ID
FROM PURCHASE_ORDER WHERE PRODUCT_ID = :product_id ORDER BY ORDER_ID;

-- 6. 구매자마다 주문 건수(새 등록 가격 구매자는 0건 또는 1건이어야 한다)
SELECT c.BUYER_ID, COUNT(o.ORDER_ID) AS ORDER_COUNT, NVL(SUM(o.QUANTITY), 0) AS ORDER_QTY
FROM CONVERSATION c LEFT JOIN PURCHASE_ORDER o ON o.PRODUCT_ID = c.PRODUCT_ID AND o.BUYER_ID = c.BUYER_ID
WHERE c.PRODUCT_ID = :product_id
GROUP BY c.BUYER_ID ORDER BY c.BUYER_ID;

-- 7. 구매자의 잔액(대상 상품에 대화가 있는 구매자 전원)
SELECT w.MEMBER_ID, w.BALANCE, w.UPDATED_AT
FROM WALLET w WHERE w.MEMBER_ID IN (SELECT BUYER_ID FROM CONVERSATION WHERE PRODUCT_ID = :product_id)
ORDER BY w.MEMBER_ID;

-- 8. 구매자의 잔액 변동 내역(충전과 결제, 주문 연결)
SELECT t.TRANSACTION_ID, t.MEMBER_ID, t.TYPE, t.AMOUNT, t.BALANCE_AFTER, t.ORDER_ID, t.REQUEST_ID, t.CREATED_AT
FROM BALANCE_TRANSACTION t WHERE t.MEMBER_ID IN (SELECT BUYER_ID FROM CONVERSATION WHERE PRODUCT_ID = :product_id)
ORDER BY t.MEMBER_ID, t.TRANSACTION_ID;

-- 9. 전체 수량 대조
-- 판매 수량 초과: 주문 수량 합계 + 유효 예약 수량 합계가 최초 수량보다 크면 「초과」
-- 남은 수량 불일치: 저장된 남은 수량이 최초 수량 − 주문 수량 합계와 다르면 「다름」
SELECT p.PRODUCT_ID, p.INITIAL_QUANTITY, p.REMAINING_QUANTITY, p.STATUS,
       q.ORDER_COUNT, q.ORDER_QTY, q.VALID_RSV_COUNT, q.VALID_RSV_QTY,
       q.ORDER_QTY + q.VALID_RSV_QTY AS ORDER_PLUS_VALID_RSV,
       CASE WHEN q.ORDER_QTY + q.VALID_RSV_QTY > p.INITIAL_QUANTITY THEN '초과' ELSE '이하' END AS OVER_SALE,
       p.INITIAL_QUANTITY - q.ORDER_QTY AS REMAINING_BY_ORDERS,
       CASE WHEN p.REMAINING_QUANTITY = p.INITIAL_QUANTITY - q.ORDER_QTY THEN '같음' ELSE '다름' END AS REMAINING_CHECK
FROM PRODUCT p,
     (SELECT (SELECT COUNT(*) FROM PURCHASE_ORDER WHERE PRODUCT_ID = :product_id) AS ORDER_COUNT,
             (SELECT NVL(SUM(QUANTITY), 0) FROM PURCHASE_ORDER WHERE PRODUCT_ID = :product_id) AS ORDER_QTY,
             (SELECT COUNT(*) FROM RESERVATION WHERE PRODUCT_ID = :product_id AND STATUS = 'ACTIVE' AND EXPIRES_AT > SYS_EXTRACT_UTC(SYSTIMESTAMP)) AS VALID_RSV_COUNT,
             (SELECT NVL(SUM(QUANTITY), 0) FROM RESERVATION WHERE PRODUCT_ID = :product_id AND STATUS = 'ACTIVE' AND EXPIRES_AT > SYS_EXTRACT_UTC(SYSTIMESTAMP)) AS VALID_RSV_QTY
      FROM DUAL) q
WHERE p.PRODUCT_ID = :product_id;

ROLLBACK;
