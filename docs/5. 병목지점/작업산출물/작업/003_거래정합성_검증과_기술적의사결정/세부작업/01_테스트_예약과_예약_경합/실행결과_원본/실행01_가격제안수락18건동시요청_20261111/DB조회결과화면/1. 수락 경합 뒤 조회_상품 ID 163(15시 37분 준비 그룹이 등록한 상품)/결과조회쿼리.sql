-- 가격 제안과 예약 대조: 수락한 가격 제안마다 같은 구매자에게 제안 수량 전부가 예약됐는지,
-- 응답 대기로 남은 가격 제안에 예약이 없는지
SELECT o.OFFER_ID, o.BUYER_ID, o.QUANTITY AS OFFER_QTY, o.STATUS AS OFFER_STATUS,
       r.RESERVATION_ID, r.BUYER_ID AS RSV_BUYER, r.CONVERSATION_ID AS RSV_CONV,
       o.CONVERSATION_ID AS OFFER_CONV, r.QUANTITY AS RSV_QTY, r.STATUS AS RSV_STATUS
  FROM PRICE_OFFER o
  LEFT JOIN RESERVATION r ON r.OFFER_ID = o.OFFER_ID
 WHERE o.PRODUCT_ID = 163
 ORDER BY o.OFFER_ID;

-- 예약 중인 예약의 건수와 수량 합계
SELECT COUNT(*) AS ACTIVE_COUNT, NVL(SUM(QUANTITY), 0) AS ACTIVE_SUM
  FROM RESERVATION
 WHERE PRODUCT_ID = 163
   AND STATUS = 'ACTIVE';