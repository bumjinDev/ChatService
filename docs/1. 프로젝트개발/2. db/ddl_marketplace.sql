-- ddl_marketplace.sql
-- C2C Marketplace 신규 테이블 DDL (Oracle, 스키마 TOYCHAT 또는 별도 테스트 스키마)
--
-- 기준 문서 : docs/4. 프로젝트고도화/3. C2C_Marketplace_설계_명세서.md 4.2절(2.1판)
-- 실행 계정 : 테이블을 만들 스키마의 계정 본인
-- 선행 조건 : ddl_toychat.sql 의 MEMBERTBL 이 먼저 존재하고 ID 에 기본키(PK_MEMBERTBL)가 있어야 한다(회원 FK 대상). 기본키가 없으면 ORA-02270 이 난다(판단 기록 J-30).
--
-- 작성 규칙
--   1) ddl-auto: none 이므로 Hibernate 는 이 스크립트를 실행하지 않는다.
--      엔티티의 @Table/@Column 이름과 아래 식별자가 그대로 일치해야 한다.
--   2) 식별자는 따옴표 없는 대문자로 쓴다(ddl_toychat.sql 과 같은 규칙).
--   3) 숫자 PK 는 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY, 금액은 NUMBER(15),
--      수량은 NUMBER(10), 시각은 TIMESTAMP(6)(UTC 값 저장), 열거형은 VARCHAR2(30).
--   4) FK 는 회원·상품·대화·주문과 적용 제안에 대한 참조에만 둔다(설계 4.1·4.2).
--   5) 동시 요청을 막기 위한 UNIQUE 제약과 성능 목적의 인덱스는 이번 범위에서 두지 않는다
--      (설계 1.1·4.1). SHIPMENT·REFUND_REQUEST 의 "주문당 하나" 규칙은 순차 요청에서
--      서비스의 현재 상태 검사로 지킨다.
--   6) 시각 사이의 관계(예: INSPECTION_DEADLINE_AT = DELIVERED_AT + 48시간)는
--      애플리케이션이 계산해서 저장하며 CHECK 제약으로 두지 않는다.
--
-- 실행 순서 : 부모 → 자식
--   1) PRODUCT  2) WALLET  3) CONVERSATION  4) PRICE_OFFER  5) PURCHASE_ORDER
--   6) SHIPMENT  7) REFUND_REQUEST  8) CHAT_MESSAGE  9) BALANCE_TRANSACTION
--
-- 되돌리기 : 아래 [DROP] 블록을 자식 → 부모 순서로 실행한다. 기존 테이블은 건드리지 않는다.
--------------------------------------------------------------------------------


